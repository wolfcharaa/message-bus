CREATE TABLE __SCHEMA__.message_bus__schema_migrations (
    component text NOT NULL,
    migration_id text NOT NULL,
    artifact_checksum char(64) NOT NULL,
    installation_fingerprint char(64) NOT NULL,
    library_version text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (component, migration_id)
);

CREATE TABLE __SCHEMA__.message_bus__messages (
    message_id text PRIMARY KEY,
    correlation_id text NOT NULL,
    causation_id text NULL,
    role text NOT NULL CHECK (role IN ('command', 'event')),
    message_name text NOT NULL,
    payload_version integer NOT NULL CHECK (payload_version > 0),
    codec text NOT NULL,
    content_type text NOT NULL,
    object_graph_fingerprint char(64) NULL,
    payload bytea NOT NULL,
    payload_digest char(64) NOT NULL,
    metadata jsonb NOT NULL,
    recorded_at timestamptz NOT NULL
);

CREATE INDEX message_bus__messages_correlation_idx
    ON __SCHEMA__.message_bus__messages (correlation_id, recorded_at, message_id);

CREATE TABLE __SCHEMA__.message_bus__deliveries (
    delivery_id text PRIMARY KEY,
    enqueue_sequence bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    message_id text NOT NULL REFERENCES __SCHEMA__.message_bus__messages(message_id) ON DELETE CASCADE,
    target_id text NOT NULL,
    handler_class text NOT NULL,
    handler_method text NOT NULL,
    route text NOT NULL DEFAULT 'postgres',
    lane text NOT NULL,
    policy jsonb NOT NULL,
    state text NOT NULL CHECK (state IN (
        'staged', 'accepted', 'running', 'retry_wait',
        'succeeded', 'failed', 'cancelled', 'outcome_unknown'
    )),
    priority integer NOT NULL,
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    current_attempt_id text NULL,
    available_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    cancellation_requested boolean NOT NULL DEFAULT false,
    cancellation_requested_at timestamptz NULL,
    replay_of text NULL REFERENCES __SCHEMA__.message_bus__deliveries(delivery_id),
    last_failure_category text NULL,
    accepted_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    started_at timestamptz NULL,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    finished_at timestamptz NULL
);

CREATE INDEX message_bus__deliveries_claim_idx
    ON __SCHEMA__.message_bus__deliveries (lane, priority DESC, available_at, enqueue_sequence)
    WHERE state IN ('accepted', 'retry_wait') AND cancellation_requested = false;

CREATE INDEX message_bus__deliveries_terminal_idx
    ON __SCHEMA__.message_bus__deliveries (finished_at, delivery_id)
    WHERE state IN ('succeeded', 'failed', 'cancelled', 'outcome_unknown');

CREATE INDEX message_bus__deliveries_message_target_idx
    ON __SCHEMA__.message_bus__deliveries (message_id, target_id, delivery_id);

CREATE TABLE __SCHEMA__.message_bus__delivery_attempts (
    attempt_id text PRIMARY KEY,
    delivery_id text NOT NULL REFERENCES __SCHEMA__.message_bus__deliveries(delivery_id) ON DELETE CASCADE,
    attempt_number integer NOT NULL CHECK (attempt_number > 0),
    worker_id text NOT NULL,
    child_pid integer NULL,
    lease_token text NOT NULL,
    state text NOT NULL DEFAULT 'running' CHECK (state IN (
        'running', 'succeeded', 'failed', 'cancelled', 'lost', 'outcome_unknown'
    )),
    started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    handler_started_at timestamptz NULL,
    heartbeat_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    lease_expires_at timestamptz NOT NULL,
    finished_at timestamptz NULL,
    lost_at timestamptz NULL,
    outcome text NULL,
    failure_category text NULL,
    failure_summary text NULL,
    scheduling_decision text NULL,
    UNIQUE (delivery_id, attempt_number)
);

CREATE INDEX message_bus__delivery_attempts_recovery_idx
    ON __SCHEMA__.message_bus__delivery_attempts (lease_expires_at, attempt_id)
    WHERE finished_at IS NULL;

ALTER TABLE __SCHEMA__.message_bus__deliveries
    ADD CONSTRAINT message_bus__deliveries_current_attempt_fk
    FOREIGN KEY (current_attempt_id)
    REFERENCES __SCHEMA__.message_bus__delivery_attempts(attempt_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE __SCHEMA__.message_bus__delivery_operations (
    operation_id text PRIMARY KEY,
    delivery_id text NOT NULL REFERENCES __SCHEMA__.message_bus__deliveries(delivery_id) ON DELETE CASCADE,
    idempotency_key text NULL,
    kind text NOT NULL CHECK (kind IN ('cancel', 'replay')),
    actor text NOT NULL,
    reason text NOT NULL,
    reference text NULL,
    initiator_metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    outcome text NOT NULL,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX message_bus__delivery_operations_delivery_idx
    ON __SCHEMA__.message_bus__delivery_operations (delivery_id, recorded_at);

CREATE UNIQUE INDEX message_bus__delivery_operations_idempotency_idx
    ON __SCHEMA__.message_bus__delivery_operations (idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE TABLE __SCHEMA__.message_bus__legacy_delivery_map (
    legacy_queue_job_id bigint PRIMARY KEY,
    delivery_id text NOT NULL UNIQUE REFERENCES __SCHEMA__.message_bus__deliveries(delivery_id) ON DELETE CASCADE,
    imported_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
